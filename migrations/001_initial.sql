CREATE TABLE eightlm.users (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email TEXT UNIQUE NOT NULL, salt TEXT NOT NULL, password_hash TEXT NOT NULL
);
CREATE TABLE eightlm.sessions (
 token TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES eightlm.users(id) ON DELETE CASCADE,
 expires BIGINT NOT NULL
);
CREATE INDEX sessions_expiry ON eightlm.sessions(expires);
CREATE TABLE eightlm.workspaces (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL);
CREATE TABLE eightlm.members (
 workspace_id INTEGER REFERENCES eightlm.workspaces(id) ON DELETE CASCADE,
 user_id INTEGER REFERENCES eightlm.users(id) ON DELETE CASCADE,
 role TEXT NOT NULL CHECK (role IN ('Owner','Admin','Editor','Publisher','Viewer')),
 PRIMARY KEY(workspace_id,user_id)
);
CREATE UNIQUE INDEX one_owner_per_workspace ON eightlm.members(workspace_id) WHERE role='Owner';
CREATE INDEX members_user ON eightlm.members(user_id);
CREATE TABLE eightlm.invites (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 workspace_id INTEGER NOT NULL REFERENCES eightlm.workspaces(id) ON DELETE CASCADE,
 email TEXT NOT NULL, role TEXT NOT NULL CHECK (role IN ('Admin','Editor','Publisher','Viewer')),
 hash TEXT UNIQUE NOT NULL, expires BIGINT NOT NULL,
 UNIQUE(workspace_id,email)
);
CREATE TABLE eightlm.activity (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 workspace_id INTEGER NOT NULL REFERENCES eightlm.workspaces(id) ON DELETE CASCADE,
 actor TEXT NOT NULL, action TEXT NOT NULL, created BIGINT NOT NULL
);
CREATE INDEX activity_workspace ON eightlm.activity(workspace_id,id DESC);
